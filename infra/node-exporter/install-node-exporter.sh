#!/usr/bin/env bash
# Installs Prometheus node_exporter on a VM (Ubuntu, amd64) for host metrics.
# The cluster's Elastic Agent scrapes it (Fleet: Prometheus integration).
#
#   scp infra/node-exporter/install-node-exporter.sh cerberus-admin@10.0.1.4:/tmp/
#   ssh cerberus-admin@10.0.1.4 'sudo bash /tmp/install-node-exporter.sh 10.0.1.4 10.0.2.4'
#   ssh cerberus-admin@10.0.2.4 'sudo bash /tmp/install-node-exporter.sh 10.0.2.4 10.42.0.0/16'
#
# Args: <listen-ip> <allowed scraper ip/cidr>[,<more>...]
#
# - Upstream release, SHA-256 checked against the release's sha256sums.txt
#   (Ubuntu 22.04's package is 1.3.1 from 2021, built with an old Go).
# - Listens on the private IP only, never 0.0.0.0.
# - iptables: a NODE_EXPORTER chain accepts the allowed sources and drops
#   everyone else on port 9100. Bootstrap VM: the k3s node (pod traffic
#   leaving the cluster is SNATed to it). k3s node: the pod CIDR (a pod
#   reaching its own node keeps its pod IP). Rebuilt on every service
#   start, because neither VM has a persistent firewall.
# - Runs as a transient DynamicUser with a read-only system and a 64 MB cap.
set -euo pipefail

LISTEN_IP="${1:?usage: install-node-exporter.sh <listen-ip> <allowed-sources, comma-separated>}"
ALLOWED="${2:?usage: install-node-exporter.sh <listen-ip> <allowed-sources, comma-separated>}"
VERSION="${NODE_EXPORTER_VERSION:-1.13.1}"
PORT=9100

[ "$(id -u)" -eq 0 ] || { echo "run as root (sudo)" >&2; exit 1; }

tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
base="https://github.com/prometheus/node_exporter/releases/download/v${VERSION}"
tarball="node_exporter-${VERSION}.linux-amd64.tar.gz"
curl -fsSL -o "$tmp/$tarball" "$base/$tarball"
curl -fsSL -o "$tmp/sha256sums.txt" "$base/sha256sums.txt"
(cd "$tmp" && grep " ${tarball}\$" sha256sums.txt | sha256sum -c -)
tar -xzf "$tmp/$tarball" -C "$tmp"
install -m 0755 -o root -g root "$tmp/node_exporter-${VERSION}.linux-amd64/node_exporter" /usr/local/bin/node_exporter

cat > /usr/local/sbin/node-exporter-firewall <<FWEOF
#!/bin/sh
# Generated by infra/node-exporter/install-node-exporter.sh
set -e
iptables -N NODE_EXPORTER 2>/dev/null || iptables -F NODE_EXPORTER
for src in $(echo "${ALLOWED}" | tr ',' ' '); do iptables -A NODE_EXPORTER -s "\$src" -j ACCEPT; done
iptables -A NODE_EXPORTER -j DROP
iptables -C INPUT -p tcp --dport ${PORT} -j NODE_EXPORTER 2>/dev/null || iptables -I INPUT 1 -p tcp --dport ${PORT} -j NODE_EXPORTER
# Older installs used a single DROP rule in INPUT; remove it if present.
iptables -S INPUT | grep -- "--dport ${PORT} -j DROP" | sed "s/^-A /-D /" | while read -r r; do iptables \$r; done
FWEOF
chmod 0755 /usr/local/sbin/node-exporter-firewall
cat > /etc/systemd/system/node_exporter.service <<EOF
[Unit]
Description=Prometheus node_exporter (host metrics, scraped by Elastic Agent)
After=network-online.target
Wants=network-online.target

[Service]
# "+" runs the firewall step as root; the exporter itself runs unprivileged.
ExecStartPre=+/usr/local/sbin/node-exporter-firewall
ExecStart=/usr/local/bin/node_exporter --web.listen-address=${LISTEN_IP}:${PORT}
DynamicUser=yes
NoNewPrivileges=yes
ProtectSystem=strict
ProtectHome=read-only
PrivateTmp=yes
PrivateDevices=yes
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectControlGroups=yes
RestrictAddressFamilies=AF_INET AF_INET6 AF_UNIX AF_NETLINK
RestrictNamespaces=yes
LockPersonality=yes
MemoryMax=64M
Restart=on-failure

[Install]
WantedBy=multi-user.target
EOF

systemctl daemon-reload
systemctl enable node_exporter >/dev/null
systemctl restart node_exporter
sleep 2
systemctl is-active node_exporter
/usr/local/bin/node_exporter --version 2>&1 | head -1
ss -ltn "sport = :${PORT}"
iptables -S INPUT | grep -- "--dport ${PORT}"
iptables -S NODE_EXPORTER
